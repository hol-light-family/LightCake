(* ========================================================================= *)
(* primTypes: port of HOL4 semantics/primTypesScript.sml (CakeML v3479).     *)
(* Definition of the primitive types that are in scope before any CakeML    *)
(* program starts.  Some of them are generated by running an initial        *)
(* program.                                                                  *)
(* ========================================================================= *)

needs "semantics/semanticPrimitives.ml";;
needs "semantics/evaluate.ml";;
needs "semantics/typeSystem.ml";;

type_invention_error := true;;

(* ------------------------------------------------------------------------- *)
(* Notes on the rendering:                                                   *)
(* - The mlstring literal of x is implode "x"; set is set_of_list.           *)
(* - Record literals are written with the constructors (fields in order):    *)
(*   state_REC clock refs ffi next_type_stamp next_exn_stamp eval_state,     *)
(*   sem_env_REC v c, type_env_REC v c t.                                    *)
(* ------------------------------------------------------------------------- *)

(* The ordering in the following is important.  The stamps generated from  *)
(* the exceptions and types must match those in semanticPrimitives.         *)

let prim_types_program_def = cake_def
  `prim_types_program =
     [Dexn unknown_loc (implode "Bind") [];
      Dexn unknown_loc (implode "Chr") [];
      Dexn unknown_loc (implode "Div") [];
      Dexn unknown_loc (implode "Subscript") [];
      Dtype unknown_loc [([],implode "bool",
                          [(implode "False",[]); (implode "True",[])])];
      Dtype unknown_loc
        [([implode "'a"],implode "list",
          [(implode "[]",[]);
           (implode "::",[Atvar (implode "'a");
                          Atapp [Atvar (implode "'a")] (Short (implode "list"))])])]]`;;

let add_to_sem_env_def = cake_def
  `add_to_sem_env (st:(FFI)state,env:v sem_env) prog =
     match evaluate_decs st env prog with
       (st,Rval env') -> SOME (st,extend_dec_env env' env)
     | (st,Rerr _) -> NONE`;;

let prim_sem_env_def = cake_def
  `prim_sem_env (ffi:(FFI)ffi_state) =
     add_to_sem_env
       (state_REC 0 [] ffi 0 0 NONE,sem_env_REC nsEmpty nsEmpty)
       prim_types_program`;;

let prim_tenv_def = cake_def
  `prim_tenv =
     type_env_REC
       nsEmpty
       (alist_to_ns
          (REVERSE
             [(implode "Bind",[],[],Texn_num); (implode "Chr",[],[],Texn_num);
              (implode "Div",[],[],Texn_num); (implode "Subscript",[],[],Texn_num);
              (implode "False",[],[],Tbool_num); (implode "True",[],[],Tbool_num);
              (implode "[]",[implode "'a"],[],Tlist_num);
              (implode "::",[implode "'a"],
               [Tvar (implode "'a"); Tlist (Tvar (implode "'a"))],Tlist_num)]))
       (alist_to_ns
          (REVERSE
             [(implode "array",[implode "'a"],Tapp [Tvar (implode "'a")] Tarray_num);
              (implode "bool",[],Tapp [] Tbool_num);
              (implode "char",[],Tapp [] Tchar_num);
              (implode "double",[],Tapp [] Tdouble_num);
              (implode "exn",[],Tapp [] Texn_num);
              (implode "int",[],Tapp [] Tint_num);
              (implode "list",[implode "'a"],Tapp [Tvar (implode "'a")] Tlist_num);
              (implode "ref",[implode "'a"],Tapp [Tvar (implode "'a")] Tref_num);
              (implode "string",[],Tapp [] Tstring_num);
              (implode "unit",[],Tapp [] Ttup_num);
              (implode "vector",[implode "'a"],Tapp [Tvar (implode "'a")] Tvector_num);
              (implode "word64",[],Tapp [] Tword64_num);
              (implode "word8",[],Tapp [] Tword8_num);
              (implode "word8array",[],Tapp [] Tword8array_num)]))`;;

(* HOL4 comments in prim_tenv: Tfn is ->, specially handled; pairs are     *)
(* specially handled.                                                       *)

let prim_type_ids_def = cake_def
  `prim_type_ids = set_of_list (CONS Tlist_num (CONS Tbool_num prim_type_nums))`;;
