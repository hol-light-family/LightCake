(* ========================================================================= *)
(* machine_ieee: port of HOL4 src/floating-point/machine_ieeeScript.sml.    *)
(* Bit-vector encodings of IEEE-754 floating-point: the 64-bit encoding     *)
(* (double precision), as generated by machine_ieeeLib.mk_fp_encoding        *)
(* ("fp64", 52, 11, SOME "double").                                          *)
(*                                                                           *)
(* word64 = int64; ('t,'w) float = (T,W)float (binary_ieee.ml);              *)
(* (h >< l) w = word_subword w (l,h + 1 - l); v @@ w = word_join v w (at the *)
(* exact result width); n2w = word; (:52 # 11) = (:52#11);                  *)
(* f ## g = PAIR_MAP (vocab.ml).                                             *)
(* Not ported (not used by the closure): the 16-bit and 32-bit encodings and *)
(* the conversions between encodings (convert, fp16_to_fp32, ...), and the   *)
(* evaluation forms that HOL4 stores under the operation names (fp64_add,   *)
(* ...).                                                                     *)
(* ========================================================================= *)

needs "hol4/vocab.ml";;
needs "hol4/binary_ieee.ml";;

new_type_abbrev("double",`:(52,11)float`);;

(* ------------------------------------------------------------------------- *)
(* The 64-bit encoding                                                       *)
(* ------------------------------------------------------------------------- *)

let fp64_to_float_def = new_definition
  `fp64_to_float (w:int64) =
     float_REC (word_subword w (63,1)) (word_subword w (52,11))
               (word_subword w (0,52)) :double`;;

let float_to_fp64_def = new_definition
  `float_to_fp64 (x:double) =
     (word_join (float_Sign x)
        (word_join (float_Exponent x) (float_Significand x):63 word) :int64)`;;

let fp64_to_real_def = new_definition
  `fp64_to_real = float_to_real o fp64_to_float`;;

let fp64_to_value_def = new_definition
  `fp64_to_value = float_value o fp64_to_float`;;

let real_to_fp64_def = new_definition
  `real_to_fp64 mode = float_to_fp64 o real_to_float mode`;;

let real_to_fp64_with_flags_def = new_definition
  `real_to_fp64_with_flags mode =
     (I ## float_to_fp64) o real_to_float_with_flags mode`;;

let int_to_fp64_def = new_definition
  `int_to_fp64 mode (a:int) = real_to_fp64 mode (real_of_int a)`;;

let fp64_roundToIntegral_def = new_definition
