(* ------------------------------------------------------------------------- *)
(* The encoding is a bijection                                               *)
(* ------------------------------------------------------------------------- *)

let float_to_fp64_fp64_to_float = prove
 (`!x:int64. float_to_fp64 (fp64_to_float x) = x`,
  GEN_TAC THEN REWRITE_TAC[fp64_to_float_def; float_to_fp64_def;
                           float_accessors] THEN
  BITBLAST_TAC);;

let fp64_to_float_float_to_fp64 = prove
 (`!x:double. fp64_to_float (float_to_fp64 x) = x`,
  GEN_TAC THEN REWRITE_TAC[fp64_to_float_def; float_to_fp64_def] THEN
  REWRITE_TAC[float_component_equality; float_accessors] THEN
  REPEAT CONJ_TAC THEN BITBLAST_TAC);;

let fp64_to_float_11 = prove
 (`!x y:int64. fp64_to_float x = fp64_to_float y <=> x = y`,
  MESON_TAC[float_to_fp64_fp64_to_float]);;

let float_to_fp64_11 = prove
 (`!x y:double. float_to_fp64 x = float_to_fp64 y <=> x = y`,
  MESON_TAC[fp64_to_float_float_to_fp64]);;

let fp64_nchotomy = prove
 (`!x:int64. ?y. x = float_to_fp64 y`,
  MESON_TAC[float_to_fp64_fp64_to_float]);;

let float_fp64_nchotomy = prove
 (`!x:double. ?y. x = fp64_to_float y`,
  MESON_TAC[fp64_to_float_float_to_fp64]);;

(* HOL4 states this with DIVMOD_2EXP 52 n and DIVMOD_2EXP 11 q (bit theory): *)
(* here the quotients and remainders are written out.                        *)

let fp64_to_float_n2w = prove
 (`!n. fp64_to_float (word n) =
       float_REC (word ((n DIV 2 EXP 52 DIV 2 EXP 11) MOD 2))
                 (word ((n DIV 2 EXP 52) MOD 2 EXP 11))
                 (word (n MOD 2 EXP 52))`,
  GEN_TAC THEN REWRITE_TAC[fp64_to_float_def] THEN
  SIMP_TAC[WORD_SUBWORD_WORD; DIMINDEX_64; ARITH] THEN
  REWRITE_TAC[DIV_DIV; GSYM EXP_ADD; EXP; DIV_1; EXP_1] THEN
  CONV_TAC NUM_REDUCE_CONV);;

(* ------------------------------------------------------------------------- *)
(* Sanity checks of the semantics (not HOL4 theorems): values of some       *)
(* encodings, exact operations, conversions to integers (ties to even),     *)
(* comparisons and special values.  The words are the IEEE-754 encodings:    *)
(*   4607182418800017408 = 0x3FF0000000000000 =  1.0                         *)
(*   4611686018427387904 = 0x4000000000000000 =  2.0                         *)
(*   4602678819172646912 = 0x3FE0000000000000 =  0.5                         *)
(*   4613937818241073152 = 0x4008000000000000 =  3.0                         *)
(*   4616189618054758400 = 0x4010000000000000 =  4.0                         *)
(*   4612811918334230528 = 0x4004000000000000 =  2.5                         *)
(*   4615063718147915776 = 0x400C000000000000 =  3.5                         *)
(*  13836183955189006336 = 0xC004000000000000 = -2.5                         *)
(*  13835058055282163712 = 0xC000000000000000 = -2.0                         *)
(*   9218868437227405311 = 0x7FEFFFFFFFFFFFFF = largest finite double        *)
(*   9218868437227405312 = 0x7FF0000000000000 = +infinity                    *)
(*   9221120237041090560 = 0x7FF8000000000000 = a quiet NaN                  *)
(*   9223372036854775808 = 0x8000000000000000 = -0.0                         *)
(* ------------------------------------------------------------------------- *)

let LIEEE_FP64_REDUCE_TAC =
  REWRITE_TAC[fp64_to_real_def; fp64_to_value_def; fp64_isNan_def; o_THM;
              fp64_to_float_n2w; float_is_finite_Exponent; float_is_zero] THEN
  CONV_TAC NUM_REDUCE_CONV THEN
  REWRITE_TAC[float_to_real_def; float_value_def; float_is_nan_def;
              float_accessors; VAL_WORD; word_UINT_MAX] THEN
  CONV_TAC(DEPTH_CONV DIMINDEX_CONV) THEN CONV_TAC NUM_REDUCE_CONV THEN
  CONV_TAC WORD_REDUCE_CONV THEN
  REWRITE_TAC[float_value_CASE; float_value_11] THEN
  CONV_TAC REAL_RAT_REDUCE_CONV;;

let LIEEE_FP64_VALUES = prove
 (`fp64_to_real (word 4607182418800017408) = &1 /\
   fp64_to_real (word 4602678819172646912) = &1 / &2 /\
   fp64_to_real (word 13835058055282163712) = -- &2 /\
   fp64_to_real (word 1) = inv (&2 pow 1074) /\
   fp64_to_real (word 9218868437227405311) =
     (&2 - inv (&2 pow 52)) * &2 pow 1023 /\
   fp64_to_real (word 9223372036854775808) = &0 /\
   fp64_to_value (word 9218868437227405312) = Infinity /\
   fp64_isNan (word 9221120237041090560)`,
  REPEAT CONJ_TAC THEN LIEEE_FP64_REDUCE_TAC);;

let LIEEE_FP64_LARGEST_THRESHOLD = prove
 (`largest(:52#11) = (&2 - inv (&2 pow 52)) * &2 pow 1023 /\
   threshold(:52#11) = (&2 - inv (&2 pow 53)) * &2 pow 1023 /\
   fp64_to_real (word 9218868437227405311) = largest(:52#11)`,
  REWRITE_TAC[largest_def; threshold_def] THEN
  CONV_TAC(DEPTH_CONV DIMINDEX_CONV) THEN CONV_TAC NUM_REDUCE_CONV THEN
  REPEAT CONJ_TAC THENL
   [CONV_TAC REAL_RAT_REDUCE_CONV; CONV_TAC REAL_RAT_REDUCE_CONV;
    LIEEE_FP64_REDUCE_TAC]);;

(* rounding (ties to even) a finite non-zero double gives it back            *)

let LIEEE_REAL_TO_FP64_FP64_TO_REAL = prove
 (`!w:int64.
     fp64_isFinite w /\ ~fp64_isZero w
     ==> real_to_fp64 roundTiesToEven (fp64_to_real w) = w`,
  REWRITE_TAC[fp64_isFinite_def; fp64_isZero_def; fp64_to_real_def;
              real_to_fp64_def; real_to_float_def; o_THM] THEN
  SIMP_TAC[LIEEE_FLOAT_ROUND_FINITE_FLOAT; float_to_fp64_fp64_to_float]);;

let LIEEE_FP64_ROUND_WORD = prove
 (`!b x c:int64.
     float_is_finite (fp64_to_float c) /\ ~float_is_zero (fp64_to_float c) /\
     float_to_real (fp64_to_float c) = x
     ==> float_to_fp64 (float_round roundTiesToEven b x) = c`,
  REPEAT STRIP_TAC THEN FIRST_X_ASSUM(SUBST1_TAC o SYM) THEN
  ASM_SIMP_TAC[LIEEE_FLOAT_ROUND_FINITE_FLOAT; float_to_fp64_fp64_to_float]);;

let LIEEE_FP64_BINOP_TAC fin a b r1 r2 =
  MP_TAC(ISPECL [`roundTiesToEven`; mk_comb(`fp64_to_float`,a);
                 mk_comb(`fp64_to_float`,b); r1; r2] fin) THEN
  ANTS_TAC THENL [CONJ_TAC THEN LIEEE_FP64_REDUCE_TAC; DISCH_THEN SUBST1_TAC] THEN
  CONV_TAC REAL_RAT_REDUCE_CONV THEN
  REWRITE_TAC[LIEEE_SND_FLOAT_ROUND_WITH_FLAGS; rounding_distinct;
              GSYM rounding_distinct] THEN
  CONV_TAC REAL_RAT_REDUCE_CONV THEN
  MATCH_MP_TAC LIEEE_FP64_ROUND_WORD THEN REPEAT CONJ_TAC THEN
  LIEEE_FP64_REDUCE_TAC;;

