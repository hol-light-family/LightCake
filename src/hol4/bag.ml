    COND_CASES_TAC THEN REWRITE_TAC[] THEN ARITH_TAC;
    DISCH_THEN(MP_TAC o SPEC `(b:A->num) x`) THEN
    MATCH_MP_TAC(MESON[] `(a:A->num) = b ==> FINITE_BAG a ==> FINITE_BAG b`) THEN
