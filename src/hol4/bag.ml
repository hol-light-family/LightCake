  ASM_REWRITE_TAC[FILTER; LIST_TO_BAG_def; BAG_FILTER_EMPTY;
                  BAG_FILTER_BAG_INSERT] THEN
  COND_CASES_TAC THEN ASM_REWRITE_TAC[LIST_TO_BAG_def]);;

let INN_LIST_TO_BAG = prove
