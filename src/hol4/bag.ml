    FIRST_X_ASSUM(MP_TAC o SPEC `x:A` o MATCH_MP FINITE_BAG_INSERT) THEN
    MATCH_MP_TAC(MESON[] `(a:A->num) = b ==> FINITE_BAG a ==> FINITE_BAG b`) THEN
