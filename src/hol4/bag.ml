    REWRITE_TAC[SUBSET; IN_SET_OF_BAG; LSORTAUX_BAG_IN_ALT; IN_INSERT] THEN
    MESON_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `!k. FINITE_BAG (\y:A. if y = x then k else b y)` MP_TAC THENL
