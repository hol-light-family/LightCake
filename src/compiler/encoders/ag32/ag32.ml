(* ========================================================================= *)
(* ag32: port of HOL4 compiler/encoders/ag32/ag32Script.sml (CakeML v3479),  *)
(* the Silver ISA (ag32): its datatypes, the state record, the semantics of  *)
(* the instructions (Run, Next), the decoder and the encoder.  The HOL4      *)
(* script is generated by L3 and builds its terms with the Import library    *)
(* (examples/l3-machine-code/common/Import.sml); the definitions below are   *)
(* those terms, written out.                                                 *)
(*                                                                           *)
(* Notes on the rendering of the L3 idioms (Import):                         *)
(* - Construct = cake_type; Record = cake_record "ag32_state" (HOL4 s.f is   *)
(*   ag32_state_f s, s with f := v is ag32_state_f_fupd (K v) s).  HOL4's    *)
(*   Datatype gives the enumerations funcT and shiftT the bijections         *)
(*   funcT2num, num2funcT, shiftT2num, num2shiftT: defined here explicitly   *)
(*   (num2funcT and num2shiftT give ARB out of range, where HOL4's are       *)
(*   unspecified).                                                           *)
(* - Def (f, (x1,..,xn), Close (state, b)) is f (x1,..,xn) = \state. b (as   *)
(*   HOL4 states it); Def0 is a plain constant; Let (p, e, b) is let p = e   *)
(*   in b; CS (case) is match; a case on word literals (in Decode) is the    *)
(*   chain of conditionals it means.                                         *)
(* - Words (FTy n = (n)word, F8 = byte, F16 = int16, F32 = int32, F64 =      *)
(*   int64; vocabulary of hol4/words4.ml): LW (i,n) = word i; Add Sub Mul    *)
(*   on words = word_add word_sub word_mul; BAnd BOr BXor = word_and         *)
(*   word_or word_xor; Lt Ult on words = word_ilt word_ult; Neg = word_neg;  *)
(*   SE = word_sx; EX (x,h,l) = word_extract h l x; CC (right-nested         *)
(*   concatenation, HOL4 @@ at the summed width) = word_join at that width;  *)
(*   BFI (31,23,x,w) = bit_field_insert 31 23 x w = word_insert w (23,9) x;  *)
(*   Lsl Lsr Asr Ror by a word (HOL4 <<~ >>>~ >>~ #>>~, word_lsl_bv ...)     *)
(*   are written out as their definitions word_shl a (val b), word_ushr,     *)
(*   word_ishr, word_ror a (val b).                                          *)
(* - Casts (Import pickCast): word to word = word_zx, to num = val, to int   *)
(*   = ival, to bool = ~(w = word 0), to an enumeration = num2funcT (val w)  *)
(*   (num2shiftT); num to word = word; bool to word = v2w [b]; bool to num   *)
(*   = if b then 1 else 0; enumeration to word = word (funcT2num x).         *)
(* - Fupd (m,i,e) = (i =+ e) m; LU (HOL4 ()) = one; BL (32,w) =              *)
(*   boolify32 w, defined here as HOL4 bitstringLib defines it, with         *)
(*   bitify32 and the four theorems bitstringLib proves of them.             *)
(* - Names: the constructors Reg Imm Jump Out Shift and the constants shift  *)
(*   norm Run Decode Next Encode get the prefix ag32_ (they clash with       *)
(*   constructors of asm, ast, labLang, word_bignum, with a constant of      *)
(*   clos_annotate or HOL Light names, or are generic L3 names); HOL4 enc is *)
(*   ag32_enc' (ag32_enc is ag32_target's, and enc is a common variable      *)
(*   name).                                                                  *)
(* - Variables: HOL4 negate (dfn'LoadConstant) is neg here (negate was a     *)
(*   constant of stack_to_lab, now stack_to_lab_negate); the anonymous unit  *)
(*   argument of HOL4 incPC                                                  *)
(*   (Import AVar uTy) is u.                                                 *)
(* - Helpers that are not HOL4 theorems have the prefix AG32AUX_.            *)
(* ========================================================================= *)

