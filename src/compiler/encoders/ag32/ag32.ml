(* HOL4 Datatype: the bijections of the enumerated types with 0 .. 15 and   *)
(* 0 .. 3 (an index out of range gives ARB, unspecified as in HOL4)         *)

let funcT2num_def = cake_def
  `(funcT2num fAdd = 0) /\ (funcT2num fAddWithCarry = 1) /\
   (funcT2num fSub = 2) /\ (funcT2num fCarry = 3) /\
   (funcT2num fOverflow = 4) /\ (funcT2num fInc = 5) /\
   (funcT2num fDec = 6) /\ (funcT2num fMul = 7) /\
   (funcT2num fMulHU = 8) /\ (funcT2num fAnd = 9) /\
   (funcT2num fOr = 10) /\ (funcT2num fXor = 11) /\
   (funcT2num fEqual = 12) /\ (funcT2num fLess = 13) /\
   (funcT2num fLower = 14) /\ (funcT2num fSnd = 15)`;;

let num2funcT_def = cake_def
  `num2funcT n =
     if n = 0 then fAdd else if n = 1 then fAddWithCarry
     else if n = 2 then fSub else if n = 3 then fCarry
     else if n = 4 then fOverflow else if n = 5 then fInc
     else if n = 6 then fDec else if n = 7 then fMul
     else if n = 8 then fMulHU else if n = 9 then fAnd
     else if n = 10 then fOr else if n = 11 then fXor
     else if n = 12 then fEqual else if n = 13 then fLess
     else if n = 14 then fLower else if n = 15 then fSnd
     else (ARB:funcT)`;;

let shiftT2num_def = cake_def
  `(shiftT2num shiftLL = 0) /\ (shiftT2num shiftLR = 1) /\
   (shiftT2num shiftAR = 2) /\ (shiftT2num shiftRor = 3)`;;

let num2shiftT_def = cake_def
  `num2shiftT n =
     if n = 0 then shiftLL else if n = 1 then shiftLR
     else if n = 2 then shiftAR else if n = 3 then shiftRor
     else (ARB:shiftT)`;;

(* -- the semantics of the instructions -- *)

let ALU_def = cake_def
  `ALU (func,a:int32,b:int32) =
     \state:ag32_state.
       match func with
         fAdd ->
           let ret = word_add a b in
           (ret,
            ag32_state_OverflowFlag_fupd (combin_K (~(ival ret = ival a + ival b)))
              (ag32_state_CarryFlag_fupd (combin_K (2 EXP 32 <= val a + val b)) state))
       | fAddWithCarry ->
           (word_add (word_add a b) (v2w [ag32_state_CarryFlag state]),
            ag32_state_CarryFlag_fupd
              (combin_K (2 EXP 32 <=
                  (val a + val b) + (if ag32_state_CarryFlag state then 1 else 0)))
              state)
       | fSub ->
           let ret = word_sub a b in
           (ret,
            ag32_state_OverflowFlag_fupd (combin_K (~(ival ret = ival a - ival b))) state)
       | fCarry -> (v2w [ag32_state_CarryFlag state],state)
       | fOverflow -> (v2w [ag32_state_OverflowFlag state],state)
       | fInc -> (word_add a (word 1),state)
       | fDec -> (word_sub a (word 1),state)
       | fMul -> (word_mul a b,state)
       | fMulHU ->
           (word_extract 63 32 (word_mul (word_zx a) (word_zx b):int64),state)
       | fAnd -> (word_and a b,state)
       | fOr -> (word_or a b,state)
       | fXor -> (word_xor a b,state)
       | fEqual -> (v2w [a = b],state)
       | fLess -> (v2w [word_ilt a b],state)
       | fLower -> (v2w [word_ult a b],state)
       | fSnd -> (b,state)`;;

let ag32_shift_def = cake_def
  `ag32_shift (shiftOp,a:int32,b:int32) =
     match shiftOp with
       shiftLL -> word_shl a (val b)
     | shiftLR -> word_ushr a (val b)
     | shiftAR -> word_ishr a (val b)
     | shiftRor -> word_ror a (val b)`;;

let incPC_def = cake_def
  `incPC (u:one) =
     \state. ag32_state_PC_fupd (combin_K (word_add (ag32_state_PC state) (word 4))) state`;;

let ag32_norm_def = cake_def
  `ag32_norm (func,wback,out,w:(6)word,a:int32,b:int32) =
     \state.
       let (v,s) = ALU (func,a,b) state in
       let s = if wback then ag32_state_R_fupd (combin_K ((w =+ v) (ag32_state_R s))) s
               else s in
       incPC one (if out then ag32_state_data_out_fupd (combin_K (word_zx v)) s else s)`;;

let ri2word_def = cake_def
  `ri2word ri =
     \state. match ri with
               ag32_Reg i -> ag32_state_R state i
             | ag32_Imm v -> (word_sx v:int32)`;;

let dfn'LoadUpperConstant_def = cake_def
  `dfn'LoadUpperConstant (reg,imm:(9)word) =
     \state.
       incPC one
         (ag32_state_R_fupd
            (combin_K ((reg =+ word_insert (ag32_state_R state reg) (23,9) imm)
                (ag32_state_R state)))
            state)`;;

let dfn'LoadConstant_def = cake_def
  `dfn'LoadConstant (reg,neg,imm:(23)word) =
     \state.
       let v = (word_zx imm:int32) in
       incPC one
         (ag32_state_R_fupd
            (combin_K ((reg =+ (if neg then word_neg v else v)) (ag32_state_R state)))
            state)`;;

let dfn'Normal_def = cake_def
  `dfn'Normal (func,w,a,b) =
     \state. ag32_norm (func,T,F,w,ri2word a state,ri2word b state) state`;;

let dfn'Shift_def = cake_def
  `dfn'Shift (shiftOp,w,a,b) =
     \state.
       incPC one
         (ag32_state_R_fupd
            (combin_K ((w =+ ag32_shift (shiftOp,ri2word a state,ri2word b state))
                (ag32_state_R state)))
            state)`;;

let dfn'StoreMEM_def = cake_def
  `dfn'StoreMEM (a,b) =
     \state.
       let v = ri2word a state in
       let alignedAddr =
         (word_join (word_extract 31 2 (ri2word b state):(30)word)
                    (word 0:(2)word):int32) in
       let s = ag32_state_MEM_fupd
                 (combin_K ((alignedAddr =+ word_extract 7 0 v) (ag32_state_MEM state)))
                 state in
       let s = ag32_state_MEM_fupd
                 (combin_K ((word_add alignedAddr (word 1) =+ word_extract 15 8 v)
                     (ag32_state_MEM s)))
                 s in
       let s = ag32_state_MEM_fupd
                 (combin_K ((word_add alignedAddr (word 2) =+ word_extract 23 16 v)
                     (ag32_state_MEM s)))
                 s in
       incPC one
         (ag32_state_MEM_fupd
            (combin_K ((word_add alignedAddr (word 3) =+ word_extract 31 24 v)
                (ag32_state_MEM s)))
            s)`;;

let dfn'StoreMEMByte_def = cake_def
  `dfn'StoreMEMByte (a,b) =
     \state.
       incPC one
         (ag32_state_MEM_fupd
            (combin_K ((ri2word b state =+ word_extract 7 0 (ri2word a state))
                (ag32_state_MEM state)))
            state)`;;

let dfn'LoadMEM_def = cake_def
  `dfn'LoadMEM (w,a) =
     \state.
       let alignedAddr =
         (word_join (word_extract 31 2 (ri2word a state):(30)word)
                    (word 0:(2)word):int32) in
       incPC one
         (ag32_state_R_fupd
            (combin_K ((w =+
                 (word_join (ag32_state_MEM state (word_add alignedAddr (word 3)))
                   (word_join (ag32_state_MEM state (word_add alignedAddr (word 2)))
                      (word_join (ag32_state_MEM state (word_add alignedAddr (word 1)))
                         (ag32_state_MEM state alignedAddr):int16):(24)word):int32))
                (ag32_state_R state)))
            state)`;;

let dfn'LoadMEMByte_def = cake_def
  `dfn'LoadMEMByte (w,a) =
     \state.
       incPC one
         (ag32_state_R_fupd
            (combin_K ((w =+ (word_zx (ag32_state_MEM state (ri2word a state)):int32))
                (ag32_state_R state)))
            state)`;;

let dfn'Out_def = cake_def
  `dfn'Out (func,w,a,b) =
     \state. ag32_norm (func,T,T,w,ri2word a state,ri2word b state) state`;;

let dfn'In_def = cake_def
  `dfn'In w =
     \state.
       incPC one
         (ag32_state_R_fupd
            (combin_K ((w =+ (word_zx (ag32_state_data_in state):int32))
                (ag32_state_R state)))
            state)`;;

let accelerator_f_def = cake_def
  `accelerator_f (arg:int32) =
     (word_zx (word_add (word_extract 31 16 arg:int16) (word_extract 15 0 arg))
      :int32)`;;

let dfn'Accelerator_def = cake_def
  `dfn'Accelerator (w,a) =
     \state.
       incPC one
         (ag32_state_R_fupd
            (combin_K ((w =+ accelerator_f (ri2word a state)) (ag32_state_R state)))
            state)`;;

let dfn'Jump_def = cake_def
  `dfn'Jump (func,w,a) =
     \state.
       let s = (let (v,s) = ALU (func,ag32_state_PC state,ri2word a state) state in
                ag32_state_PC_fupd (combin_K v) s) in
       ag32_state_R_fupd
         (combin_K ((w =+ word_add (ag32_state_PC state) (word 4)) (ag32_state_R s))) s`;;

let dfn'JumpIfZero_def = cake_def
  `dfn'JumpIfZero (func,w,a,b) =
     \state.
       let (v,s) = (let (v,s) = ALU (func,ri2word a state,ri2word b state) state in
                    ((v = word 0),s)) in
       if v then ag32_state_PC_fupd (combin_K (word_add (ag32_state_PC s) (ri2word w s))) s
       else incPC one s`;;

let dfn'JumpIfNotZero_def = cake_def
  `dfn'JumpIfNotZero (func,w,a,b) =
     \state.
       let (v,s) = (let (v,s) = (let (v,s) = ALU (func,ri2word a state,ri2word b state)
                                               state in
                                 ((v = word 0),s)) in
                    (~v,s)) in
       if v then ag32_state_PC_fupd (combin_K (word_add (ag32_state_PC s) (ri2word w s))) s
       else incPC one s`;;

let dfn'Interrupt_def = cake_def
  `dfn'Interrupt state =
     incPC one
       (ag32_state_io_events_fupd
          (combin_K (APPEND (ag32_state_io_events state) [ag32_state_MEM state])) state)`;;

let dfn'ReservedInstr_def = new_definition
  `dfn'ReservedInstr = one`;;

let ag32_Run_def = cake_def
  `ag32_Run v0 =
     \state.
       match v0 with
         Interrupt -> dfn'Interrupt state
       | ReservedInstr -> state
       | Accelerator v1 -> dfn'Accelerator v1 state
       | In v2 -> dfn'In v2 state
       | ag32_Jump v3 -> dfn'Jump v3 state
       | JumpIfNotZero v4 -> dfn'JumpIfNotZero v4 state
       | JumpIfZero v5 -> dfn'JumpIfZero v5 state
       | LoadConstant v6 -> dfn'LoadConstant v6 state
       | LoadMEM v7 -> dfn'LoadMEM v7 state
       | LoadMEMByte v8 -> dfn'LoadMEMByte v8 state
       | LoadUpperConstant v9 -> dfn'LoadUpperConstant v9 state
       | Normal v10 -> dfn'Normal v10 state
       | ag32_Out v11 -> dfn'Out v11 state
       | ag32_Shift v12 -> dfn'Shift v12 state
       | StoreMEM v13 -> dfn'StoreMEM v13 state
       | StoreMEMByte v14 -> dfn'StoreMEMByte v14 state`;;

let DecodeReg_imm_def = cake_def
  `DecodeReg_imm (flag:(1)word,v) =
     if flag = word 0 then ag32_Reg v else ag32_Imm v`;;

