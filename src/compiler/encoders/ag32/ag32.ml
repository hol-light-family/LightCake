let boolify32bitify32 = prove
 (`!x. boolify32 (bitify32 x) = x`,
  REWRITE_TAC[FORALL_PAIR_THM; bitify32_def; boolify32_v2w]);;
let bitify32boolify32 = prove
 (`!w. bitify32 (boolify32 w) = w`,
  GEN_TAC THEN REWRITE_TAC[boolify32_def; bitify32_def; WORD_EQ_BITS_ALT; DIMINDEX_32] THEN
