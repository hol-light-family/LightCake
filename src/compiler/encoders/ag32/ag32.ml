 (`!n. boolify32 (word n) =
       let n1 = DIV2 n in let n2 = DIV2 n1 in let n3 = DIV2 n2 in let n4 = DIV2 n3 in
       let n5 = DIV2 n4 in let n6 = DIV2 n5 in let n7 = DIV2 n6 in let n8 = DIV2 n7 in
       let n9 = DIV2 n8 in let n10 = DIV2 n9 in let n11 = DIV2 n10 in let n12 = DIV2 n11 in
       let n13 = DIV2 n12 in let n14 = DIV2 n13 in let n15 = DIV2 n14 in
       let n16 = DIV2 n15 in let n17 = DIV2 n16 in let n18 = DIV2 n17 in
       let n19 = DIV2 n18 in let n20 = DIV2 n19 in let n21 = DIV2 n20 in
       let n22 = DIV2 n21 in let n23 = DIV2 n22 in let n24 = DIV2 n23 in
       let n25 = DIV2 n24 in let n26 = DIV2 n25 in let n27 = DIV2 n26 in
       let n28 = DIV2 n27 in let n29 = DIV2 n28 in let n30 = DIV2 n29 in
       let n31 = DIV2 n30 in
       (ODD n31,ODD n30,ODD n29,ODD n28,ODD n27,ODD n26,ODD n25,ODD n24,ODD n23,ODD n22,
        ODD n21,ODD n20,ODD n19,ODD n18,ODD n17,ODD n16,ODD n15,ODD n14,ODD n13,ODD n12,
        ODD n11,ODD n10,ODD n9,ODD n8,ODD n7,ODD n6,ODD n5,ODD n4,ODD n3,ODD n2,ODD n1,
