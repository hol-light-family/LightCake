  GEN_TAC THEN REWRITE_TAC[boolify32_def; BIT_WORD; DIMINDEX_32] THEN
  CONV_TAC(TOP_DEPTH_CONV let_CONV) THEN REWRITE_TAC[DIV2_DEF; DIV_DIV] THEN
  CONV_TAC NUM_REDUCE_CONV THEN REWRITE_TAC[DIV_1]);;

(* helper: bit i (v2w l) for a numeral i and a list literal l *)

let AG32AUX_BIT_V2W_CONV =
  let th = prove
   (`!n (v:bool list). bit n (v2w v:N word) <=>
       n < dimindex(:N) /\ n < LENGTH v /\ EL (LENGTH v - 1 - n) v`,
    REWRITE_TAC[bit_v2w; testbit]) in
  let cnv = GEN_REWRITE_CONV I [th] THENC
            DEPTH_CONV (DIMINDEX_CONV ORELSEC LENGTH_CONV ORELSEC NUM_RED_CONV) THENC
            REWRITE_CONV[] THENC TRY_CONV (ONCE_DEPTH_CONV EL_CONV) in
  fun tm -> match tm with
     Comb(Comb(Const("bit",_),n),Comb(Const("v2w",_),l)) when is_numeral n -> cnv tm
   | _ -> failwith "AG32AUX_BIT_V2W_CONV";;

