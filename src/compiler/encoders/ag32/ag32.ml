let funcT_INDUCT,funcT_RECURSION = cake_type
  "funcT = fAdd | fAddWithCarry | fSub | fCarry | fOverflow | fInc | fDec
         | fMul | fMulHU | fAnd | fOr | fXor | fEqual | fLess | fLower | fSnd";;

let shiftT_INDUCT,shiftT_RECURSION = cake_type
  "shiftT = shiftLL | shiftLR | shiftAR | shiftRor";;

let reg_immT_INDUCT,reg_immT_RECURSION = cake_type
  "reg_immT = ag32_Imm ((6)word) | ag32_Reg ((6)word)";;

let instruction_INDUCT,instruction_RECURSION = cake_type
  "instruction =
     Accelerator ((6)word # reg_immT)
   | In ((6)word)
   | Interrupt
   | ag32_Jump (funcT # (6)word # reg_immT)
   | JumpIfNotZero (funcT # reg_immT # reg_immT # reg_immT)
   | JumpIfZero (funcT # reg_immT # reg_immT # reg_immT)
   | LoadConstant ((6)word # bool # (23)word)
   | LoadMEM ((6)word # reg_immT)
   | LoadMEMByte ((6)word # reg_immT)
   | LoadUpperConstant ((6)word # (9)word)
   | Normal (funcT # (6)word # reg_immT # reg_immT)
   | ag32_Out (funcT # (6)word # reg_immT # reg_immT)
   | ReservedInstr
   | ag32_Shift (shiftT # (6)word # reg_immT # reg_immT)
   | StoreMEM (reg_immT # reg_immT)
   | StoreMEMByte (reg_immT # reg_immT)";;

