  REWRITE_TAC[]);;

let ag32_Decode_def = cake_def
  `ag32_Decode (opc:int32) =
     let (b'31,b'30,b'29,b'28,b'27,b'26,b'25,b'24,b'23,b'22,b'21,b'20,b'19,b'18,
          b'17,b'16,b'15,b'14,b'13,b'12,b'11,b'10,b'9,b'8,b'7,b'6,b'5,b'4,b'3,b'2,
          b'1,b'0) = boolify32 opc in
     if ~b'31 /\ b'24 /\ ~b'23 /\ ~b'22 /\ ~b'21 /\ ~b'20 /\ ~b'19 /\ ~b'18 /\
        ~b'17 /\ ~b'16 /\ ~b'15 /\ ~b'14 /\ ~b'13 /\ ~b'12 /\ ~b'11 /\ ~b'10 /\ ~b'9
     then LoadUpperConstant (v2w [b'30;b'29;b'28;b'27;b'26;b'25],
                             v2w [b'8;b'7;b'6;b'5;b'4;b'3;b'2;b'1;b'0])
     else if b'31 /\ b'24
     then LoadConstant (v2w [b'30;b'29;b'28;b'27;b'26;b'25],
                        ~(v2w [b'23] = word 0:(1)word),
                        v2w [b'22;b'21;b'20;b'19;b'18;b'17;b'16;b'15;b'14;b'13;
                             b'12;b'11;b'10;b'9;b'8;b'7;b'6;b'5;b'4;b'3;b'2;b'1;b'0])
     else if b'24 then ReservedInstr
     else
       let Op = (v2w [b'5;b'4;b'3;b'2;b'1;b'0]:(6)word) in
       let OpArg = (v2w [b'9;b'8;b'7;b'6]:(4)word) in
       let w = DecodeReg_imm (v2w [b'31],v2w [b'30;b'29;b'28;b'27;b'26;b'25]) in
       let a = DecodeReg_imm (v2w [b'23],v2w [b'22;b'21;b'20;b'19;b'18;b'17]) in
       let b = DecodeReg_imm (v2w [b'16],v2w [b'15;b'14;b'13;b'12;b'11;b'10]) in
       let func = num2funcT (val OpArg) in
       if Op = word 10 then JumpIfZero (func,w,a,b)
       else if Op = word 11 then JumpIfNotZero (func,w,a,b)
       else if Op = word 12 then Interrupt
       else match w with
              ag32_Imm _ -> ReservedInstr
            | ag32_Reg wi ->
                if Op = word 0 then Normal (func,wi,a,b)
                else if Op = word 1
                then ag32_Shift (num2shiftT (val (word_extract 1 0 OpArg:(2)word)),
                                 wi,a,b)
                else if Op = word 2 then StoreMEM (a,b)
                else if Op = word 3 then StoreMEMByte (a,b)
                else if Op = word 4 then LoadMEM (wi,a)
                else if Op = word 5 then LoadMEMByte (wi,a)
                else if Op = word 6 then ag32_Out (func,wi,a,b)
                else if Op = word 7 then In wi
                else if Op = word 8 then Accelerator (wi,a)
                else if Op = word 9 then ag32_Jump (func,wi,a)
                else ReservedInstr`;;

let ag32_Next_def = cake_def
  `ag32_Next state =
     let v = (word_join (word_extract 31 2 (ag32_state_PC state):(30)word)
                        (word 0:(2)word):int32) in
     ag32_Run
       (ag32_Decode
          (word_join (ag32_state_MEM state (word_add v (word 3)))
             (word_join (ag32_state_MEM state (word_add v (word 2)))
                (word_join (ag32_state_MEM state (word_add v (word 1)))
                   (ag32_state_MEM state v):int16):(24)word):int32))
       state`;;

let ri2bits_def = cake_def
  `ri2bits ri =
     match ri with
       ag32_Reg i -> (word_join (word 0:(1)word) i:(7)word)
     | ag32_Imm v -> (word_join (word 1:(1)word) v:(7)word)`;;

let ag32_enc'_def = cake_def
  `ag32_enc' (func,w,a,b,opc:(6)word) =
     (word_join (ri2bits w)
        (word_join (word 0:(1)word)
           (word_join (ri2bits a)
              (word_join (ri2bits b)
                 (word_join (word (funcT2num func):(4)word) opc:(10)word)
               :(17)word):(24)word):(25)word):int32)`;;

let encShift_def = cake_def
  `encShift (shift,w,a,b,opc:(6)word) =
     (word_join (ri2bits w)
        (word_join (word 0:(1)word)
           (word_join (ri2bits a)
              (word_join (ri2bits b)
                 (word_join (word (shiftT2num shift):(4)word) opc:(10)word)
               :(17)word):(24)word):(25)word):int32)`;;

let ag32_Encode_def = cake_def
  `ag32_Encode i =
     match i with
       LoadUpperConstant (Rw,const) ->
         (word_join (word 0:(1)word)
            (word_join Rw
               (word_join (word 1:(1)word)
                  (word_join (word 0:(15)word) const:(24)word):(25)word):(31)word)
          :int32)
     | LoadConstant (Rw,neg,const) ->
         (word_join (word 1:(1)word)
            (word_join Rw
               (word_join (word 1:(1)word)
                  (word_join (v2w [neg]:(1)word) const:(24)word):(25)word):(31)word)
          :int32)
     | Normal (func,w,a,b) -> ag32_enc' (func,ag32_Reg w,a,b,word 0)
     | ag32_Shift (shift,w,a,b) -> encShift (shift,ag32_Reg w,a,b,word 1)
     | StoreMEM (a,b) -> ag32_enc' (fAdd,ag32_Reg (word 0),a,b,word 2)
     | StoreMEMByte (a,b) -> ag32_enc' (fAdd,ag32_Reg (word 0),a,b,word 3)
     | LoadMEM (w,a) -> ag32_enc' (fAdd,ag32_Reg w,a,ag32_Imm (word 0),word 4)
     | LoadMEMByte (w,a) -> ag32_enc' (fAdd,ag32_Reg w,a,ag32_Imm (word 0),word 5)
     | ag32_Out (func,w,a,b) -> ag32_enc' (func,ag32_Reg w,a,b,word 6)
     | In w ->
         ag32_enc' (fAdd,ag32_Reg w,ag32_Imm (word 0),ag32_Imm (word 0),word 7)
     | Accelerator (w,a) -> ag32_enc' (fAdd,ag32_Reg w,a,ag32_Imm (word 0),word 8)
     | ag32_Jump (func,w,a) -> ag32_enc' (func,ag32_Reg w,a,ag32_Imm (word 0),word 9)
     | JumpIfZero (func,w,a,b) -> ag32_enc' (func,w,a,b,word 10)
     | JumpIfNotZero (func,w,a,b) -> ag32_enc' (func,w,a,b,word 11)
     | Interrupt ->
         ag32_enc' (fAdd,ag32_Imm (word 0),ag32_Imm (word 0),ag32_Imm (word 0),
                    word 12)
     | _ -> word 63`;;
